// Writes dist/index.d.ts as a thin re-export of the vue-tsc declarations under
// dist/types. Keeps the package `types` field pointed at a stable path.
import { writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const typesEntry = resolve(root, 'dist/types/index.d.ts');
if (!existsSync(typesEntry)) {
  console.error('[emit-dts-entry] dist/types/index.d.ts missing — run vue-tsc first.');
  process.exit(1);
}

const content = `// Type entry for ania-avatar-vue. Re-exports the vue-tsc-emitted declarations
// from ./types. Generated by \`npm run build\` (do not edit by hand).
export * from './types/index';
export { default } from './types/index';
`;
writeFileSync(resolve(root, 'dist/index.d.ts'), content, 'utf8');
console.log('[emit-dts-entry] wrote dist/index.d.ts');
